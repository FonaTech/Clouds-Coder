@dataclass
class NodeInfo:
    """One source module top-level statement."""

    order: int
    name: str
    kind: str
    lineno: int
    end_lineno: int
    source_start: int
    source_end: int
    source_hash: str = ""
    target_module: str = ""
    bound_names: List[str] = field(default_factory=list)
    bases: List[str] = field(default_factory=list)
    generated_ast_index: int = -1


@dataclass
class ManifestEntry:
    order: int
    name: str
    kind: str
    lineno: int
    end_lineno: int
    source_start: int
    source_end: int
    source_hash: str
    target_module: str
    bound_names: List[str] = field(default_factory=list)
    generated_ast_index: int = -1


@dataclass
class SplitManifest:
    source_path: str
    source_hash: str
    output_dir: str
    package_name: str
    generator_version: str = GENERATOR_VERSION
    source_statement_count: int = 0
    nodes: List[ManifestEntry] = field(default_factory=list)
    layout_config: str = ""

    FILENAME = ".split_manifest.json"

    def save(self, output_dir: Path) -> None:
        (output_dir / self.FILENAME).write_text(
            json.dumps(asdict(self), indent=2, ensure_ascii=False),
            encoding="utf-8",
        )

    @classmethod
    def load(cls, output_dir: Path) -> Optional["SplitManifest"]:
        path = output_dir / cls.FILENAME
        if not path.exists():
            return None
        try:
            data = json.loads(path.read_text(encoding="utf-8"))
            if str(data.get("generator_version", "")) != GENERATOR_VERSION:
                return None
            data["nodes"] = [ManifestEntry(**row) for row in data.get("nodes", [])]
            return cls(**data)
        except Exception:
            return None


@dataclass(frozen=True)
class ImportAlias:
    name: str
    asname: Optional[str] = None

    @property
    def bound_name(self) -> str:
        return self.asname or self.name.split(".")[0]


@dataclass
class ImportStatement:
    kind: str
    lineno: int
    end_lineno: int
    bound_names: Set[str] = field(default_factory=set)


